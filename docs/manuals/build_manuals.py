def _font(run, size=None, color=None, bold=None, italic=None, name=FONT):
    run.font.name = name
    rPr = run._element.get_or_add_rPr()
    rf = rPr.find(qn('w:rFonts'))
    if rf is None:
        rf = OxmlElement('w:rFonts')
        rPr.append(rf)
    for a in ('w:ascii', 'w:hAnsi', 'w:cs', 'w:eastAsia'):
        rf.set(qn(a), name)
    if size:
        run.font.size = Pt(size)
    if color is not None:
        run.font.color.rgb = color
    if bold is not None:
        run.font.bold = bold
    if italic is not None:
        run.font.italic = italic
    return run


def _shade(cell, hex_fill):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement('w:shd')
    shd.set(qn('w:val'), 'clear')
    shd.set(qn('w:color'), 'auto')
    shd.set(qn('w:fill'), hex_fill)
    tcPr.append(shd)


def _borders(table, color='C9C3DA', inside=True):
    tblPr = table._tbl.tblPr
    b = OxmlElement('w:tblBorders')
    for edge in ('top', 'left', 'bottom', 'right') + (('insideH',) if inside else ()):
        e = OxmlElement(f'w:{edge}')
        e.set(qn('w:val'), 'single' if edge in ('top', 'bottom', 'insideH') else 'nil')
        e.set(qn('w:sz'), '4')
        e.set(qn('w:color'), color)
        b.append(e)
    tblPr.append(b)


class Doc:
    def __init__(self, title: str, subtitle: str, kicker: str):
        self.d = Document()
        s = self.d.sections[0]
        s.page_width, s.page_height = Cm(21), Cm(29.7)
        s.left_margin = s.right_margin = Cm(2.0)
        s.top_margin, s.bottom_margin = Cm(1.8), Cm(1.8)
        st = self.d.styles['Normal']
        st.font.name, st.font.size = FONT, Pt(10.5)
        st.element.rPr.rFonts.set(qn('w:eastAsia'), FONT)
        st.paragraph_format.space_after = Pt(6)
        st.paragraph_format.line_spacing = 1.2
        self.h1n = 0
        # колонтитул с номером страницы
        fp = s.footer.paragraphs[0]
        _font(fp.add_run(f'Контроль качества DXA · {title.lower()} · стр. '), 8, INK3)
        r = fp.add_run()
        for tag, text in (('begin', None), (None, 'PAGE'), ('end', None)):
            if tag:
                fc = OxmlElement('w:fldChar')
                fc.set(qn('w:fldCharType'), tag)
                r._r.append(fc)
            else:
                it = OxmlElement('w:instrText')
                it.text = text
                r._r.append(it)
        _font(r, 8, INK3)
        # титул
        icon = ROOT / 'desktop' / 'assets' / 'icon.png'
        if icon.exists():
            self.d.add_paragraph().add_run().add_picture(str(icon), width=Cm(1.8))
        self.p(kicker.upper(), 9, PINK, bold=True, after=4, before=18)
        self.p(title, 26, PURPLE, bold=True, after=4, line=1.0)
        self.p(subtitle, 13, INK2, after=14, line=1.25)
        self.rule()

    # ------------------------------------------------------------------ текст
    def p(self, text='', size=10.5, color=INK, bold=False, italic=False, after=6, before=0, line=1.25):
        para = self.d.add_paragraph()
        pf = para.paragraph_format
        pf.space_after, pf.space_before, pf.line_spacing = Pt(after), Pt(before), line
        if text:
            self.runs(para, text, size, color, bold, italic)
        return para

    @staticmethod
    def runs(para, text, size=10.5, color=INK, bold=False, italic=False):
        """**жирный** и `моно` внутри строки."""
        import re
        for part in re.split(r'(\*\*[^*]+\*\*|`[^`]+`)', text):
            if not part:
                continue
            if part.startswith('**'):
                _font(para.add_run(part[2:-2]), size, color, True, italic)
            elif part.startswith('`'):
                _font(para.add_run(part[1:-1]), size - 0.5, PURPLE, False, italic, name='Consolas')
            else:
                _font(para.add_run(part), size, color, bold, italic)

    def h1(self, text):
        self.h1n += 1
        para = self.p(after=6, before=16, line=1.1)
        para.paragraph_format.keep_with_next = True
        _font(para.add_run(f'{self.h1n}  '), 16, PINK, True)
        _font(para.add_run(text), 16, PURPLE, True)

    def h2(self, text):
        para = self.p(text, 12, PURPLE, bold=True, after=4, before=10, line=1.1)
        para.paragraph_format.keep_with_next = True

    def bullets(self, items):
        for it in items:
            para = self.p(after=3, line=1.25)
            para.paragraph_format.left_indent = Cm(0.55)
            para.paragraph_format.first_line_indent = Cm(-0.55)
            _font(para.add_run('▪  '), 10, PINK, True)
            self.runs(para, it)

    def steps(self, items):
        for i, it in enumerate(items, 1):
            para = self.p(after=4, line=1.25)
            para.paragraph_format.left_indent = Cm(0.7)
            para.paragraph_format.first_line_indent = Cm(-0.7)
            _font(para.add_run(f'{i}.  '), 10.5, PINK, True)
            self.runs(para, it)

    def note(self, title, text, fill='FFD6E3'):
        t = self.d.add_table(rows=1, cols=1)
        t.alignment = WD_TABLE_ALIGNMENT.CENTER
        c = t.cell(0, 0)
        _shade(c, fill)
        para = c.paragraphs[0]
        para.paragraph_format.space_after = Pt(2)
        _font(para.add_run(title + '  '), 10, PURPLE, True)
        self.runs(para, text, 10, INK)
        self.p(after=2)

    def table(self, rows, widths_cm, header=True, size=9.5):
        t = self.d.add_table(rows=len(rows), cols=len(rows[0]))
        t.alignment = WD_TABLE_ALIGNMENT.CENTER
        _borders(t)
        for i, row in enumerate(rows):
            for j, val in enumerate(row):
                c = t.cell(i, j)
                c.width = Cm(widths_cm[j])
                para = c.paragraphs[0]
                para.paragraph_format.space_after = Pt(1)
                para.paragraph_format.line_spacing = 1.1
                if header and i == 0:
                    _font(para.add_run(str(val).upper()), 8.5, PURPLE, True)
                else:
                    self.runs(para, str(val), size, INK)
        self.p(after=2)
        return t

    def figure(self, path: Path, caption: str, width_cm=16.0):
        if not path.exists():
            return
        para = self.p(after=2, before=4)
        para.paragraph_format.keep_with_next = True
        para.add_run().add_picture(str(path), width=Cm(width_cm))
        self.p(caption, 8.5, INK3, italic=True, after=10)

    def figures2(self, paths_caps, width_cm=7.6):
        t = self.d.add_table(rows=2, cols=len(paths_caps))
        t.alignment = WD_TABLE_ALIGNMENT.CENTER
        for j, (path, cap) in enumerate(paths_caps):
            if path.exists():
                t.cell(0, j).paragraphs[0].add_run().add_picture(str(path), width=Cm(width_cm))
            _font(t.cell(1, j).paragraphs[0].add_run(cap), 8.5, INK3, italic=True)
        self.p(after=4)

    def rule(self):
        para = self.d.add_paragraph()
        pPr = para._p.get_or_add_pPr()
        pbdr = OxmlElement('w:pBdr')
        b = OxmlElement('w:bottom')
        for k, v in (('val', 'single'), ('sz', '8'), ('space', '1'), ('color', 'FF0053')):
            b.set(qn(f'w:{k}'), v)
        pbdr.append(b)
        pPr.append(pbdr)

    def page_break(self):
        self.d.add_paragraph().add_run().add_break(WD_BREAK.PAGE)

    def save(self, path: Path):
        self.d.save(str(path))



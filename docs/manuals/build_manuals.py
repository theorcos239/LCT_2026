def safe_asset(path: Path, caption: str, width_cm: float):
    """Рисунок для текущей версии документа: (путь, подпись, ширина); путь None — пропустить."""
    if not NOXRAY or path.name not in XRAY:
        return path, caption, width_cm
    spec = XRAY[path.name]
    if spec is None or not path.exists():
        return None, caption, width_cm
    boxes, cap = spec
    from PIL import Image
    SAFE.mkdir(exist_ok=True)
    with Image.open(path) as im:
        im = im.convert('RGB')
        w, h = im.size
        parts = [im.crop((int(x0 * w), int(y0 * h), int(x1 * w), int(y1 * h))) for x0, y0, x1, y1 in boxes]
    width = max(p.width for p in parts)
    out = Image.new('RGB', (width, sum(p.height for p in parts)), (16, 19, 26))
    y = 0
    for p in parts:
        out.paste(p, (0, y))
        y += p.height
    dst = SAFE / path.name
    out.save(dst)
    return dst, cap or caption, width_cm * width / w

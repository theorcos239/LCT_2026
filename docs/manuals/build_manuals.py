def to_pdf(paths: list[Path]) -> bool:
    """PDF и встраивание Montserrat — через Word; без него остаются только DOCX."""
    try:
        import pythoncom
        import win32com.client
    except ImportError:
        return False
    pythoncom.CoInitialize()
    w = None
    try:
        w = win32com.client.DispatchEx('Word.Application')
        w.Visible = False
        for p in paths:
            doc = w.Documents.Open(str(p))
            doc.EmbedTrueTypeFonts = True
            doc.SaveSubsetFonts = True
            doc.Save()
            doc.ExportAsFixedFormat(str(p.with_suffix('.pdf')), 17)     # wdExportFormatPDF
            print(p.with_suffix('.pdf'), doc.ComputeStatistics(2), 'стр.')
            doc.Close(False)
        return True
    except Exception as e:                                               # noqa: BLE001
        print('Word недоступен:', e)
        return False
    finally:
        if w is not None:
            w.Quit()


def main() -> int:
    paths = [app_manual(), bot_manual()]
    for p in paths:
        print(p)
    to_pdf(paths)
    return 0



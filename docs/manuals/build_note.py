def _import_manuals():
    """build_manuals может в этот момент редактироваться — подождать и повторить."""
    last = None
    for attempt in range(5):
        try:
            import importlib
            import build_manuals
            importlib.reload(build_manuals)
            return build_manuals.Doc, build_manuals.to_pdf
        except (ImportError, SyntaxError) as e:              # файл не дописан
            last = e
            print(f'build_manuals не импортируется ({e}); повтор через 60 с, попытка {attempt + 1} из 5')
            time.sleep(60)
    raise last


def _f(x, nd=2):
    import numpy as np
    return '—' if x is None or (isinstance(x, float) and not np.isfinite(x)) else f'{x:.{nd}f}'


def _ci(m: dict, key: str) -> str:
    lo, hi = m.get(f'{key}_ci', [None, None])
    if lo is None:
        return ''
    return f' [{lo:.2f}–{hi:.2f}]'


def _pct(x) -> str:
    return f'{100 * x:.0f} %'


def _set_footer(d, text: str):
    """Колонтитул: требуемый текст и номер страницы."""
    from docx.oxml import OxmlElement
    from docx.oxml.ns import qn
    from build_manuals import INK3, _font
    fp = d.d.sections[0].footer.paragraphs[0]
    for r in list(fp.runs):
        r._r.getparent().remove(r._r)
    _font(fp.add_run(text + ' · стр. '), 8, INK3)
    r = fp.add_run()
    for tag, instr in (('begin', None), (None, 'PAGE'), ('end', None)):
        if tag:
            fc = OxmlElement('w:fldChar')
            fc.set(qn('w:fldCharType'), tag)
            r._r.append(fc)
        else:
            it = OxmlElement('w:instrText')
            it.text = instr
            r._r.append(it)
    _font(r, 8, INK3)



def team() -> dict:
    """Данные команды: team.json, если заполнен, иначе заглушки в квадратных скобках."""
    p = HERE / 'team.json'
    t = dict(TEAM_DEFAULT)
    if p.exists():
        t.update(json.loads(p.read_text(encoding='utf-8')))
    return t


def _f(x, nd=2):
    return '—' if x is None or (isinstance(x, float) and not np.isfinite(x)) else f'{x:.{nd}f}'


def _r(x, nd=2):
    """Число для чтения вслух: десятичная запятая."""
    return _f(x, nd).replace('.', ',')


